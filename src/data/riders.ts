type RiderId = string;

function rider(
  id: RiderId,
  name: string,
  age: number,
  nationality: string,
  number: number,
  stats: RiderStats,
  overall: number,
  potential: number,
  salary: number,
  championship: ChampionshipId,
  opts?: Partial<Rider>
): Rider {
  return {
    id,
    name,
    age,
    nationality,
    number,
    stats,
    overall,
    potential,
    salary,
    morale: 75,
    injuredForRounds: 0,
    careerWins: Math.floor(overall / 15),
    careerPodiums: Math.floor(overall / 8),
    championships: Math.floor(overall / 25),
    legacyPlate: 'none',
    isFemale: false,
    teamId: null,
    classId: null,
    championship,
    bench: false,
    ...opts,
  };
}

