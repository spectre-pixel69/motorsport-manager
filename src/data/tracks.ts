export function getAllTracks(): TrackDetails[] {
  return [
    ...GP_TRACKS_DB,
    ...SBK_TRACKS_DB,
    ...NAMC_STADIUM_TRACKS_DB,
    ...NAMC_OUTDOOR_TRACKS_DB,
  ];
}

export function getTrackById(id: string): TrackDetails | undefined {
  return getAllTracks().find(t => t.id === id);
}

export function getTracksByDiscipline(discipline: 'gp' | 'sbk' | 'namc'): TrackDetails[] {
  return getAllTracks().filter(t => t.discipline === discipline);
}

export function getTracksByKind(kind: 'road' | 'stadium' | 'outdoor'): TrackDetails[] {
  return getAllTracks().filter(t => t.kind === kind);
}
