/**
 * Comprehensive Track Database for Paddock Boss v0.1
 *
 * This module provides detailed track specifications for realistic weather simulation,
 * terrain effects, and strategic decision-making. Each track includes:
 * - Elevation and soil/asphalt characteristics
 * - Typical weather patterns by season (dry/light rain/heavy rain probability)
 * - Historical weather events (monsoons, extreme heat, etc.)
 * - Drainage rating (1-5) for water management
 * - Safety factors (runoff, walls, water hazards)
 *
 * Data sources: Historical race broadcasts, weather archives, track information from NAMC rulebook.
 */

export interface TrackDetails {
  id: string;
  name: string;
  location: string;
  discipline: 'gp' | 'sbk' | 'namc';
  kind: 'road' | 'stadium' | 'outdoor';

  // ---- Terrain Characteristics
  elevation: number;                           // meters above sea level
  soilType?: 'loam' | 'sand' | 'hardpack' | 'clay' | 'mixed' | 'volcanic'; // motocross tracks
  asphaltType?: 'bitumen' | 'chip-seal' | 'concrete'; // road courses

  // ---- Lap/Course Data
  lengthKm: number;                           // track length
  baseLapSec: number;                         // baseline lap time (100-rated rider)

  // ---- Weather Patterns (probability 0-1 per season)
  weatherBias: number;                        // baseline rain probability (0-1)
  seasonalWeather: {
    spring: { dry: number; lightRain: number; heavyRain: number };
    summer: { dry: number; lightRain: number; heavyRain: number };
    fall: { dry: number; lightRain: number; heavyRain: number };
    winter: { dry: number; lightRain: number; heavyRain: number };
  };

  // ---- Historical Weather Events
  historicalEvents: {
    event: string;                            // e.g., "Summer monsoons"
    frequency: 'rare' | 'occasional' | 'common'; // likelihood
    season: string;                           // when it occurs
    impact: string;                           // effect on racing
  }[];

  // ---- Drainage & Surface Conditions
  drainageRating: number;                     // 1 (poor) to 5 (excellent)
  drainageNotes: string;                      // why it drains well/poorly
  waterHazards: string[];                     // "standing water at turn 3", etc.

  // ---- Safety Factors
  safetyFactors: {
    runoff: 'gravel' | 'tarmac' | 'grass' | 'mixed' | 'barriers';
    wallsPresent: boolean;
    wallHeight?: string;                      // "2m concrete wall turn 7"
    waterHazardPresent: boolean;
    hazardDescription?: string;               // "creek at turn 12"
    overtakeZones: number;                    // estimated # of safe overtaking spots
    crashRiskRating: number;                  // 1 (safe) to 10 (dangerous)
  };

  // ---- Track Characteristics for Simulation
  cornersPerLap: number;
  avgSpeed: number;                           // typical avg speed for 100-rated rider (km/h)
  specialties: string[];                      // ["high-speed corners", "technical section", "wet-weather nightmare"]
}

